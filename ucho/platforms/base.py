"""Protocols and shared type aliases for the platform abstraction layer."""

from __future__ import annotations

from collections.abc import Callable
from typing import TYPE_CHECKING, Literal, Protocol, runtime_checkable

if TYPE_CHECKING:
    from ..audio import DeviceInfo
    from ..hardware import GraphicsAdapter

Permission = Literal["granted", "denied", "unknown", "unsupported"]
WindowRef = int  # HWND on Windows, pid on macOS; 0 = none
SoundEvent = Literal["start", "stop", "cancel"]
PermissionKind = Literal["microphone", "system_audio", "accessibility"]


@runtime_checkable
class Clipboard(Protocol):
    def get_text(self) -> str | None: ...
    def set_text(self, text: str | None, private: bool = True) -> int: ...  # returns the clipboard sequence number
    def sequence(self) -> int: ...
    def offer_delayed(self, text: str, consumer_pid: int | None) -> DelayedOffer: ...  # NOT yet offered; caller calls .offer()


@runtime_checkable
class DelayedOffer(Protocol):
    rendered: bool
    confirmed: bool
    lost: bool
    def offer(self) -> None: ...
    def pump(self, seconds: float, until: Callable[[], bool] | None = None) -> bool: ...
    def restore(self, previous: str | None) -> bool: ...
    def close(self) -> None: ...


@runtime_checkable
class TextInserter(Protocol):
    def foreground(self) -> WindowRef | None: ...
    def process_of(self, window: WindowRef | None) -> int | None: ...
    def is_ours(self, window: WindowRef | None) -> bool: ...
    def is_shell(self, window: WindowRef | None) -> bool: ...
    def exists(self, window: WindowRef) -> bool: ...
    def activate(self, window: WindowRef) -> bool: ...
    def paste(self) -> None: ...
    def press_enter(self) -> None: ...
    def type_text(self, text: str) -> None: ...
    def wait_keys_released(self, limit_s: float = 1.5) -> None: ...
    def paste_label(self) -> str: ...
    def permission(self) -> Permission: ...
    def request_permission(self) -> None: ...


@runtime_checkable
class Sounds(Protocol):
    def play(self, event: SoundEvent) -> None: ...


@runtime_checkable
class GlobalHotkeys(Protocol):
    def start(self, bindings: dict[str, str]) -> dict[str, str]: ...  # name -> error message
    def escape(self, enable: bool) -> None: ...
    def stop(self) -> None: ...


@runtime_checkable
class SingleInstance(Protocol):
    def acquire(self) -> bool: ...
    def listen(self, handler: Callable[[str], None]) -> None: ...
    def signal(self, command: str) -> bool: ...
    def close(self) -> None: ...


@runtime_checkable
class ProgressBar(Protocol):
    def set(self, state: Literal["none", "normal", "indeterminate", "paused", "error"], value: float = 0.0) -> None: ...


@runtime_checkable
class Shell(Protocol):
    def set_app_identity(self) -> None: ...
    def window_handle(self, tk_window) -> int: ...
    def describe_window(self, tk_window) -> bool: ...
    def after_start(self, app_id: str, tasks: list[tuple[str, str]]) -> None: ...
    def progress(self, tk_window) -> ProgressBar | None: ...
    def start_command(self) -> list[str]: ...
    def worker_command(self, module: str, args: list[str]) -> list[str]: ...
    def autostart_get(self) -> str | None: ...
    def autostart_set(self, enabled: bool) -> bool: ...
    def open_path(self, path) -> None: ...
    def work_area(self) -> tuple[int, int, int, int] | None: ...
    def show_without_focus(self, tk_window) -> None: ...
    def set_window_icon(self, tk_window) -> None: ...
    def autostart_label(self) -> str: ...


@runtime_checkable
class InputStream(Protocol):
    def start(self) -> None: ...
    def stop(self) -> None: ...
    def close(self) -> None: ...


@runtime_checkable
class AudioBackend(Protocol):
    name: str
    def list_devices(self) -> dict: ...  # same dict as ucho.audio.list_devices()
    def open_input(self, device: DeviceInfo, channels: int, rate: int, frames: int, on_data: Callable[[bytes], None]) -> InputStream: ...
    def permission(self, kind: Literal["microphone", "system_audio"]) -> Permission: ...
    def request_permission(self, kind: Literal["microphone", "system_audio"]) -> None: ...


@runtime_checkable
class SystemInfo(Protocol):
    def ram_gb(self) -> tuple[float, float, float | None]: ...  # total, available, installed
    def cpu_name(self) -> str: ...
    def physical_cores(self) -> int | None: ...
    def cpu_features(self) -> dict[str, bool]: ...
    def adapters(self) -> list[GraphicsAdapter]: ...
    def ui_language(self) -> str | None: ...
    def reduce_motion(self) -> bool: ...


@runtime_checkable
class Fonts(Protocol):
    sans: tuple[str, ...]
    display: tuple[str, ...]
    mono: tuple[str, ...]
    numeric: tuple[str, ...]
    strong: dict[str, tuple[str, ...]]
    def icon_font(self) -> str | None: ...
    def glyphs(self) -> dict[str, str]: ...
    def ui_font_file(self, bold: bool) -> str | None: ...


@runtime_checkable
class Permissions(Protocol):
    def state(self) -> dict[str, Permission]: ...  # keys: microphone, system_audio, accessibility
    def request(self, kind: str) -> None: ...
    def settings_url(self, kind: str) -> str | None: ...
